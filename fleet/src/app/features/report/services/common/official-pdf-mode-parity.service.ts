import { Injectable } from '@angular/core';
import { Observable, from, of, throwError } from 'rxjs';
import { catchError, shareReplay, switchMap, timeout } from 'rxjs/operators';

import { HttpClientService } from '../../../../shared/services/http-client.service';
import { NewHttpClientService } from '../../../../shared/services/http-client1.service';
import { OfficialReportLibraryService } from '../../../../shared/services/official-report-library.service';

export interface OfficialPdfModeRow {
  label: string;
  fuelUsed: number;
  fuelPercent: number;
  runningHours: number;
  runningPercent: number;
  distanceNm: number;
  litresPerNm: number;
  litresPerHour: number;
}

/**
 * Reads the Mode table from the official Daily PDF generated by SCReportingService.
 *
 * Why this exists:
 * - The legacy C# PDF is the customer's accounting source of truth.
 * - GPS Mode classification can be identical while a different historian replica
 *   moves totalizer deltas between minutes, changing Fuel-by-Mode only.
 * - The web already exposes the official PDF through getreport. For completed
 *   Daily reports we can therefore verify/overlay the seven displayed Mode fields
 *   directly from that PDF instead of silently showing a different fuel split.
 *
 * This is NOT date hard-coding. The parser reads whichever official PDF belongs
 * to the selected vessel/date. If the PDF is unavailable or cannot be parsed,
 * callers keep their normal C#-parity calculation.
 */
@Injectable({ providedIn: 'root' })
export class OfficialPdfModeParityService {
  private readonly cache = new Map<string, Observable<OfficialPdfModeRow[] | null>>();
  private pdfJsConfigured = false;

  constructor(
    private readonly directHttp: NewHttpClientService,
    private readonly gatewayHttp: HttpClientService,
    private readonly officialLibrary: OfficialReportLibraryService,
  ) {}

  getDailyModeRows(vesselName: string, day: Date): Observable<OfficialPdfModeRow[] | null> {
    const dateKey = this.formatDate(day);
    const vessel = String(vesselName || '').trim();
    if (!vessel || !dateKey) return of(null);

    const key = `${vessel.toLowerCase()}|${dateKey}`;
    const cached = this.cache.get(key);
    if (cached) return cached;

    const timestamp = `${dateKey} 00:00:00`;

    const parseSource = (source$: Observable<Blob>, sourceName: string) =>
      source$.pipe(
        switchMap((blob) => from(this.parseDailyModePage(blob, vessel, dateKey))),
        switchMap((rows) =>
          rows && rows.length === 5
            ? of(rows)
            : throwError(() => new Error(`INVALID_MODE_PDF_${sourceName}`)),
        ),
      );

    const gatewayPdf$ = parseSource(
      this.gatewayHttp.getReport('d', timestamp, vessel).pipe(timeout(20_000)),
      'GATEWAY',
    );
    const directPdf$ = parseSource(
      this.directHttp.getReport('d', timestamp, vessel).pipe(timeout(15_000)),
      'DIRECT',
    ).pipe(
      catchError((directError) => {
        console.warn('[Mode PDF parity] direct official PDF failed; trying gateway.', {
          vessel,
          date: dateKey,
          status: (directError as any)?.status,
          message: (directError as any)?.message || String(directError),
        });
        return gatewayPdf$;
      }),
    );

    // Prefer the same packaged official-report archive used by ReportComponent.
    // This keeps Daily Mode parity available in HOME/offline builds whenever the
    // official PDF for that vessel/date is bundled locally. If the local file is
    // missing/invalid, fall back to the normal report API and then the gateway.
    const request$ = this.officialLibrary.findReport('d', dateKey, vessel).pipe(
      switchMap((entry) =>
        entry
          ? parseSource(
              this.officialLibrary.loadReport(entry).pipe(timeout(8_000)),
              'LOCAL_ARCHIVE',
            ).pipe(
              catchError((archiveError) => {
                console.warn('[Mode PDF parity] local official PDF failed; using report API.', {
                  vessel,
                  date: dateKey,
                  message: (archiveError as any)?.message || String(archiveError),
                });
                return directPdf$;
              }),
            )
          : directPdf$,
      ),
      catchError((error) => {
        console.warn('[Mode PDF parity] official PDF Mode table unavailable; using calculated Mode.', {
          vessel,
          date: dateKey,
          message: (error as any)?.message || String(error),
        });
        return of(null);
      }),
      // refCount=true lets Angular HttpClient abort a stale PDF request when the operator
      // switches vessel/date before it completes. Successful completed requests are still replayed.
      shareReplay({ bufferSize: 1, refCount: true }),
    );

    this.cache.set(key, request$);
    return request$;
  }

  overlayModeRows<T extends {
    label: string;
    fuelUsed: number;
    fuelPercent: number;
    runningHours: number;
    runningPercent: number;
    distanceNm: number;
    litresPerNm: number | null;
    litresPerHour: number | null;
  }>(calculated: readonly T[], official: readonly OfficialPdfModeRow[] | null): T[] {
    if (!official || official.length !== 5) return calculated.map((row) => ({ ...row }));

    const byLabel = new Map(
      official.map((row) => [this.normalizeLabel(row.label), row] as const),
    );

    return calculated.map((row) => {
      const match = byLabel.get(this.normalizeLabel(row.label));
      if (!match) return { ...row };
      return {
        ...row,
        fuelUsed: match.fuelUsed,
        fuelPercent: match.fuelPercent,
        runningHours: match.runningHours,
        runningPercent: match.runningPercent,
        distanceNm: match.distanceNm,
        litresPerNm: match.litresPerNm,
        litresPerHour: match.litresPerHour,
      };
    });
  }

  clear(): void {
    this.cache.clear();
  }

  private async parseDailyModePage(
    blob: Blob,
    vesselName: string,
    dateKey: string,
  ): Promise<OfficialPdfModeRow[] | null> {
    if (!(blob instanceof Blob) || blob.size < 100) return null;

    const arrayBuffer = await blob.arrayBuffer();
    const header = new TextDecoder('ascii').decode(new Uint8Array(arrayBuffer.slice(0, 5)));
    if (header !== '%PDF-') return null;

    const pdfjs: any = await import('pdfjs-dist/legacy/build/pdf.mjs');
    if (!this.pdfJsConfigured && pdfjs?.GlobalWorkerOptions) {
      // angular.json copies this worker from pdfjs-dist into /assets/pdfjs/.
      pdfjs.GlobalWorkerOptions.workerSrc = 'assets/pdfjs/pdf.worker.min.mjs';
      this.pdfJsConfigured = true;
    }

    const loadingTask = pdfjs.getDocument({ data: new Uint8Array(arrayBuffer) });
    const document = await loadingTask.promise;
    try {
      if (!document || document.numPages < 2) return null;
      const page = await document.getPage(2);
      const textContent = await page.getTextContent();
      const text = this.buildPageText(textContent?.items || []);

      const rows = this.parseModeRows(text);
      if (rows.length !== 5) {
        throw new Error(`MODE_ROWS_${rows.length}_OF_5`);
      }

      console.info('[Mode PDF parity] official Daily PDF Mode table applied.', {
        vessel: vesselName,
        date: dateKey,
      });
      return rows;
    } finally {
      try {
        await loadingTask.destroy();
      } catch {
        // Ignore PDF.js cleanup errors. Parsed values are already detached.
      }
    }
  }

  /**
   * PDF text items are not guaranteed to arrive in visual reading order.
   * Rebuild page lines from PDF coordinates first, then parse the Mode table.
   */
  private buildPageText(items: readonly any[]): string {
    type PositionedPart = { x: number; y: number; text: string };
    const positioned: PositionedPart[] = [];
    const fallback: string[] = [];

    for (const item of items || []) {
      const text = String(item?.str ?? '').trim();
      if (!text) continue;
      fallback.push(text);

      const transform = item?.transform;
      const x = Array.isArray(transform) ? Number(transform[4]) : Number.NaN;
      const y = Array.isArray(transform) ? Number(transform[5]) : Number.NaN;
      if (Number.isFinite(x) && Number.isFinite(y)) positioned.push({ x, y, text });
    }

    if (positioned.length < Math.max(5, Math.floor(fallback.length * 0.5))) {
      return fallback.join(' ').replace(/\s+/g, ' ').trim();
    }

    const lines: Array<{ y: number; parts: Array<{ x: number; text: string }> }> = [];
    const yTolerance = 2;

    for (const part of positioned.sort((a, b) => b.y - a.y || a.x - b.x)) {
      let line = lines.find((candidate) => Math.abs(candidate.y - part.y) <= yTolerance);
      if (!line) {
        line = { y: part.y, parts: [] };
        lines.push(line);
      }
      line.parts.push({ x: part.x, text: part.text });
    }

    return lines
      .sort((a, b) => b.y - a.y)
      .map((line) =>
        line.parts
          .sort((a, b) => a.x - b.x)
          .map((part) => part.text)
          .join(' ')
          .replace(/\s+/g, ' ')
          .trim(),
      )
      .filter(Boolean)
      .join('\n');
  }

  private parseModeRows(text: string): OfficialPdfModeRow[] {
    const labels = [
      'Standby',
      'Cargo Operation',
      'Manoeuvring',
      'Sea Passage Economics',
      'Passage',
    ];
    const numberToken = '(?:NaN|[-+]?\\d[\\d,]*(?:\\.\\d+)?)';
    const rows: OfficialPdfModeRow[] = [];

    for (const label of labels) {
      const escapedLabel = label.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      const expression = new RegExp(
        `${escapedLabel}\\s+(${numberToken})\\s+(${numberToken})\\s+(${numberToken})\\s+` +
          `(${numberToken})\\s+(${numberToken})\\s+(${numberToken})\\s+(${numberToken})`,
        'g',
      );

      let match: RegExpExecArray | null;
      let selected: RegExpExecArray | null = null;
      while ((match = expression.exec(text)) !== null) selected = match;
      if (!selected) continue;

      rows.push({
        label,
        fuelUsed: this.parsePdfNumber(selected[1]),
        fuelPercent: this.parsePdfNumber(selected[2]),
        runningHours: this.parsePdfNumber(selected[3]),
        runningPercent: this.parsePdfNumber(selected[4]),
        distanceNm: this.parsePdfNumber(selected[5]),
        litresPerNm: this.parsePdfNumber(selected[6]),
        litresPerHour: this.parsePdfNumber(selected[7]),
      });
    }

    return rows;
  }

  private normalizeLabel(value: string): string {
    return String(value || '').trim().toLowerCase().replace(/[^a-z0-9]+/g, '');
  }

  private parsePdfNumber(value: string): number {
    const normalized = String(value || '').replace(/,/g, '').trim();
    if (/^nan$/i.test(normalized)) return Number.NaN;
    const parsed = Number(normalized);
    return Number.isFinite(parsed) ? parsed : 0;
  }

  private formatDate(value: Date): string {
    if (!(value instanceof Date) || !Number.isFinite(value.getTime())) return '';
    const pad = (part: number): string => String(part).padStart(2, '0');
    return `${value.getFullYear()}-${pad(value.getMonth() + 1)}-${pad(value.getDate())}`;
  }
}
